function simCfg = rv_isar_default_config(overrides)
%RV_ISAR_DEFAULT_CONFIG 独立的仿真参数、目标、散射体、波形与开关配置模板。
%   simCfg = rv_isar_default_config() 返回 RV + ISAR 全链路的默认配置结构体。
%   simCfg = rv_isar_default_config(overrides) 将调用方传入的部分覆盖字段递归
%   合并到默认配置之上，便于在 fullpath 外部灵活定制仿真。
%
%   外部选择运行链路方式：
%     simCfg.switches.runMode = "rv";    % 仅运行测距测速链路（RV_path）
%     simCfg.switches.runMode = "isar";  % 仅运行成像链路（ISAR_path）
%     simCfg.switches.runMode = "both";  % 先跑 RV_path，再将结果传入 ISAR_path

simCfg = struct();

%% 1. 物理常量
simCfg.constants = struct( ...
    'c',     3e8, ...
    'Z',     50, ...            % 50Ω匹配负载
    'q',     1.6e-19, ...       % 单位电荷
    'lc',    1550e-9, ...       % 光波长 1550 nm
    'h',     6.62e-34, ...      % Planck 常数
    'kB',    1.38e-23, ...      % Boltzmann 常数
    'T_exp', 300, ...           % 实验室温度 300 K
    'Mach',  340, ...
    'g',     10, ...
    'win_G', 1);

%% 2. 链路运行模式与核心计算开关（纯计算，不含绘图与评估开关）
% 绘图请调用 code/plot_rv_isar_results.m，指标评估请调用 code/assess_rv_isar_results.m。
simCfg.switches = struct( ...
    'runMode',           "isar", ...     % "rv" | "isar" | "both"
    'rvLfmSpectrumMode', 'floating');    % 'floating' | 'fixedPoint' | 'idealTime'

%% 3. 目标个数、运动参数与雷达状态
% 修改 R0 / v_Mach / a_g 长度即可直接增减目标个数；也可通过 targetIndices 选子集。
simCfg.targets = struct( ...
    'R0',                    [10050;20050;30050;40050;50050;65050;75050;85050;100050;120050], ...
    'v_Mach',                ones(10, 1) * 10.2 * sqrt(2), ...
    'a_g',                   [-15, -12, -11, -10.8, -10.6, -10.3, -10.2, -10.1, -10.1, -10.1].' * sqrt(2), ...
    'targetIndices',         [], ...               % 非空时按索引切片，如 [1 2]
    'losHat_R',              [1, 0, 0], ...        % LOS 沿雷达系 +x，正距离率表示远离
    'motionLosAngleDeg',     45, ...               % 目标运动方向与 +LOS 夹角 (deg)
    'motionAzimuthDeg',      0, ...                % 横向分量绕 LOS 方位角 (deg)
    'radarPosition0_I',      [0, 0, 0], ...
    'radarReferenceTimeSec', 0, ...
    'radarMotionDirection_R',[0, 0, 0], ...
    'radarSpeedMps',         0, ...
    'dopplerSign',           -1, ...               % fD = -2*rangeRate/lambda
    'polarization',          'VV');

%% 4. 目标散射体模型设置（统一通过 lib 预设函数生成，不在链路中手写散射点坐标）
% modelTypes 支持以下任意形式（标量供全部目标共用，或 n_Targets×1 cell/string 数组异构混排）：
%   1) lib 预设函数句柄（推荐）：
%      - @scatterermodel.configs.cfg_legacy_ZXT4       % 四点锥体 ZXT（默认，Ntip=1）
%      - @scatterermodel.configs.cfg_legacy_plane4     % 四点共面圆盘（Ntip=0）
%      - @scatterermodel.configs.cfg_rigid_cross4      % 四点十字刚体点云
%      - @scatterermodel.configs.cfg_ideal_point       % 理想单散射点
%      - @uavmodel.configs.cfg_quad_small              % 小型四旋翼 UAV
%      - @uavmodel.configs.cfg_quad_heavy              % 重载四旋翼 UAV
%      - @uavmodel.configs.cfg_hex_heavy               % 重载六旋翼 UAV
%      - @() uavmodel.configs.cfg_hybrid_vtol_4plus1("transition")
%   2) 预设短名称字符串：
%      "legacyDisk" | "legacy_ZXT4" | "legacy_plane4" | "rigidPointCloud" | "point" | "uav" | ...
% overrides：可选局部参数覆盖（如 struct('radiusM', 0.5) 或 struct('alpha0', 2)），
%            可为 1×1 struct（全体共用）或 n_Targets×1 cell（逐目标覆盖）。
simCfg.scatterer = struct( ...
    'modelTypes', @scatterermodel.configs.cfg_legacy_ZXT4, ...
    'overrides',  struct());

%% 5. 测距测速（RV_path）六段 LFM 波形与一致性门限参数
% 注：RV 测速链路固定使用 fastTimeExact，不提供快时间冻结选项。
simCfg.rv = struct( ...
    'fs',      200e6, ...
    'Tr',      50e-6, ...
    'T_space', 5e-6, ...
    'T',       1.2e-3, ...
    'Ta',      1.2e-3, ...
    'fc',      12.5e9, ...
    'f_space', 5e6, ...
    'B',                  [5, 7.5, 10] * 1e6, ...
    'f1_up',              10e6, ...
    'Na',                 1, ...
    'returnGroups',       false, ... % 是否按散射体分组返回各分量回波（默认关闭，减少内存与开销）
    'fastTimeChunkSize',  [], ...    % 空/Inf 表示关闭快时间分块；仿 UAV 等数百散射点时可设为如 4096
    'scattererChunkSize', [], ...    % 空/Inf 表示关闭散射点分块；仿 UAV 时可设为如 96
    'rvConsistency', struct( ...
        'mode',                   'snrPrecision', ... % snrPrecision / legacyResolution
        'sigmaMultiplier',        2, ...
        'snrFloorDb',             0, ...
        'snrCeilingDb',           60, ...
        'delayStdFloorBins',      0.05, ...
        'noiseEstimator',         'localCfar', ...    % localCfar / robustOffTarget
        'biasCorrection',         'rankMedian', ...   % none / rankMedian
        'maxPeakRankDifference',  0, ...
        'enforceOneToOnePeakUse', true));

%% 6. ISAR 成像（ISAR_path）宽带 LFM 波形、微动姿态、本振拍频偏置与后处理参数
% frequencyBiasHz：每个目标本振相对先验目标回波的拍频起始位置 (Hz)：
%   - 正值（>0）：本振起始位于目标回波左侧（更早到达），LO_start = 2*R/c - |f_bias|/kr
%   - 负值（<0）：本振起始位于目标回波右侧（更晚到达），LO_start = 2*R/c + |f_bias|/kr
%   支持标量（全体共用）、n_Targets×1 逐目标数组，或短序列（如默认 [20e6, 45e6] 按目标循环）。
simCfg.isar = struct( ...
    'fs',                     1e9, ...
    'Tr',                     100e-6, ...
    'T',                      1e-3, ...
    'Ta',                     1e-3, ...
    'fL',                     12e9, ...
    'fH',                     18e9, ...
    'Na',                     32, ...
    'fs_scope',               200e6, ...           % FPGA/示波器侧去斜采样率
    'echoMode',               "fastTimeExact", ... % "fastTimeExact" | "stopAndGo"（仅 ISAR 可选）
    'returnGroups',           false, ...           % 是否按散射体分组返回回波（默认关闭，大幅降低内存与耗时）
    'fastTimeChunkSize',      [], ...              % 空/Inf 表示关闭快时间分块；仿 UAV 等数百散射点时可设为如 4096
    'scattererChunkSize',     [], ...              % 空/Inf 表示关闭散射点分块；仿 UAV 时可设为如 96
    'startTimeSec',           0, ...
    'frequencyBiasHz',        [20e6, 45e6], ...    % 本振拍频起始位置（正=左侧，负=右侧），默认循环 [20, 45] MHz
    'bodyRotationMode',       "spin", ...          % "constantBodyRate" | "spin" | "coneSpin" | "swingSpin" | "coneSwingSpin"
    'omegaBody_B',            [], ...              % constantBodyRate 自定义转轴角速度 [wx,wy,wz] (rad/s)，空时默认 [0,2*pi*spinFrequencyHz,0]
    'spinFrequencyHz',        1, ...               % 自旋频率 (Hz)
    'precessionFrequencyHz',  1, ...               % 锥旋/进动频率 (Hz，coneSpin / coneSwingSpin 生效)
    'precessionHalfAngleDeg', 10, ...              % 锥旋半顶角 (deg，coneSpin / coneSwingSpin 生效)
    'swingFrequencyHz',       1, ...               % 摆动频率 (Hz，swingSpin / coneSwingSpin 生效)
    'swingAngleMinDeg',       -5, ...              % 摆动最小角 (deg，swingSpin / coneSwingSpin 生效)
    'swingAngleMaxDeg',       5, ...               % 摆动最大角 (deg，swingSpin / coneSwingSpin 生效)
    'postprocess',            struct( ...          % ISAR 后处理与 RCMC 参数（原 isarpath_settings 默认值）
        'timeWindowSamples',             20000, ...
        'rangeFftPoints',                32768, ...
        'hrrfBins',                      1024, ...
        'timeMarginSamples',             128, ...
        'timeWindowMode',                "FIXED_FIRST_PULSE", ... % "FIXED_FIRST_PULSE" | "MOVING_PULSE"
        'cropCenterOffsetBinsEffective', 110, ...
        'rangeMigrationMode',            "FFT2048_SINGLE", ...    % "FFT2048_SINGLE" | "XCORR" | "MODEL_XCORR" | "NONE"
        'rangeAlignmentMode',            "INTEGER", ...           % "INTEGER" | "FRACTIONAL"
        'rcmcCorrelationPoints',         2048, ...                % 必须等于 2*hrrfBins
        'rcmcSearchRadiusBins',          16, ...                  % RCMC 允许的最大搜索位移半径 (±bins，可按需调整)
        'phaseCompensationMode',         "VARIANCE_UNIT", ...     % "VARIANCE_UNIT" | "MODEL_CV" | "MODEL_CA" | "NONE"
        'phaseThreshold',                0.12, ...                % 特显点归一化幅度方差门限
        'dispersionCompensationEnabled', true, ...                % 是否启用脉内多普勒色散补偿
        'windowType',                    "NO", ...                % 方位维加窗类型
        'slowTimeZeroPaddingFactor',     8), ...                  % 慢时间零填充倍数
    'priorAccelerationMps2',  []);                 % MODEL_CA 时提供逐目标径向加速度

if nargin >= 1 && ~isempty(overrides)
    if ~(isstruct(overrides) && isscalar(overrides))
        error('RV_ISAR_Path:InvalidConfigOverrides', ...
            'overrides must be a scalar struct.');
    end
    simCfg = merge_struct_recursive(simCfg, overrides);
end
end

function dst = merge_struct_recursive(dst, src)
names = fieldnames(src);
for k = 1:numel(names)
    name = names{k};
    if isfield(dst, name) && isstruct(dst.(name)) && isscalar(dst.(name)) && ...
            isstruct(src.(name)) && isscalar(src.(name))
        dst.(name) = merge_struct_recursive(dst.(name), src.(name));
    else
        dst.(name) = src.(name);
    end
end
end
