function [detail, summaryTbl, savedPath] = assess_rv_measurement(rvResOrMeas, assessCfg, saveOpts)
%ASSESS_RV_MEASUREMENT 独立评估 RV 链路测距测速精度并输出逐目标误差表。
%
% 功能说明：
%   从 rvpath_run 输出的 rvRes（或直接传入 rvMeasurement）中提取指定脉冲与目标的
%   测距/测速匹配统计、均值偏置及原始/校准后的绝对与相对误差，整理为结构化评估明细
%   与 MATLAB table，并支持按 saveOpts 导出至指定目录。
%
% 输入参数：
%   rvResOrMeas - 1×1 struct，rvpath_run 的输出 rvRes（含 .measurement）或直接为 rvMeasurement
%   assessCfg   - (可选) 1×1 struct，评估配置项：
%     .pulseIndex     1×1 double，待统计脉冲索引（默认 1）
%     .targetIndices  1×K double，待统计目标索引（默认全部目标 1:N）
%     .printSummary   1×1 logical，是否向命令行打印汇总信息（默认 false）
%   saveOpts    - (可选) 1×1 struct，保存配置（enable/dir/fileName/format，默认不保存）
%
% 输出参数：
%   detail      - 1×1 struct，标量级汇总指标（matchedCount/missedTargetCount/
%                 falseEstimateCount/rangeMeanBiasM/velocityMeanBiasMps/最大相对误差等）
%   summaryTbl  - K×10 table，逐目标真值、原始估计、校准估计及误差明细表
%   savedPath   - 1×1 string，表格导出路径（未保存时为 ""）

if nargin < 2 || isempty(assessCfg), assessCfg = struct(); end
if nargin < 3, saveOpts = struct(); end

if isfield(rvResOrMeas, 'measurement')
    m = rvResOrMeas.measurement;
else
    m = rvResOrMeas;
end

[nPulses, nTargets] = size(m.truthRangeM);
pulseIdx = 1;
if isfield(assessCfg, 'pulseIndex') && ~isempty(assessCfg.pulseIndex)
    pulseIdx = double(assessCfg.pulseIndex);
end
assert(isscalar(pulseIdx) && pulseIdx >= 1 && pulseIdx <= nPulses && pulseIdx == floor(pulseIdx), ...
    'assessCfg.pulseIndex 必须为 1..%d 内的整数。', nPulses);

if isfield(assessCfg, 'targetIndices') && ~isempty(assessCfg.targetIndices)
    idx = double(assessCfg.targetIndices(:));
else
    idx = (1:nTargets).';
end
printSummary = isfield(assessCfg, 'printSummary') && logical(assessCfg.printSummary);

summaryTbl = table( ...
    idx, ...
    m.truthRangeM(pulseIdx, idx).', ...
    m.rangeM(pulseIdx, idx).', ...
    m.calibratedRangeM(pulseIdx, idx).', ...
    100 .* m.rawRangeRelativeError(pulseIdx, idx).', ...
    100 .* m.calibratedRangeRelativeError(pulseIdx, idx).', ...
    m.truthVelocityMps(pulseIdx, idx).', ...
    m.velocityMps(pulseIdx, idx).', ...
    m.calibratedVelocityMps(pulseIdx, idx).', ...
    100 .* m.calibratedVelocityRelativeError(pulseIdx, idx).', ...
    'VariableNames', { ...
    'Target', 'TruthRangeM', 'RawRangeM', 'CalibratedRangeM', ...
    'RawRangeRelErrPct', 'CalibratedRangeRelErrPct', ...
    'TruthVelocityMps', 'RawVelocityMps', 'CalibratedVelocityMps', ...
    'CalibratedVelocityRelErrPct'});

detail = struct( ...
    'pulseIndex',                                pulseIdx, ...
    'targetIndices',                             idx, ...
    'matchedCount',                              m.matchedCount(pulseIdx), ...
    'missedTargetCount',                         m.missedTargetCount(pulseIdx), ...
    'falseEstimateCount',                        m.falseEstimateCount(pulseIdx), ...
    'calibrationSampleCount',                    m.calibrationSampleCount, ...
    'rangeMeanBiasM',                            m.rangeMeanBiasM, ...
    'velocityMeanBiasMps',                       m.velocityMeanBiasMps, ...
    'maxRawRangeRelativeErrorPercent',           m.maxRawRangeRelativeErrorPercent, ...
    'maxCalibratedRangeRelativeErrorPercent',    m.maxCalibratedRangeRelativeErrorPercent, ...
    'maxRawVelocityRelativeErrorPercent',        m.maxRawVelocityRelativeErrorPercent, ...
    'maxCalibratedVelocityRelativeErrorPercent', m.maxCalibratedVelocityRelativeErrorPercent, ...
    'consistencyGateMode',                       string(m.parameters.consistencyGateMode));

if printSummary
    fprintf('\n=== RV 测距测速精度评估（脉冲 #%d，门限模式：%s）===\n', ...
        pulseIdx, detail.consistencyGateMode);
    fprintf('匹配=%d，漏检=%d，额外=%d | 距离偏置=%.4f m，速度偏置=%.4f m/s\n', ...
        detail.matchedCount, detail.missedTargetCount, detail.falseEstimateCount, ...
        detail.rangeMeanBiasM, detail.velocityMeanBiasMps);
    fprintf('最大相对误差：距离 原始=%.4f%% / 校准=%.4f%% | 速度 原始=%.4f%% / 校准=%.4f%%\n', ...
        detail.maxRawRangeRelativeErrorPercent, detail.maxCalibratedRangeRelativeErrorPercent, ...
        detail.maxRawVelocityRelativeErrorPercent, detail.maxCalibratedVelocityRelativeErrorPercent);
    disp(summaryTbl);
end

savedPath = save_output_artifact(summaryTbl, "table", saveOpts, ...
    sprintf('assess_rv_measurement_p%d', pulseIdx));
end
