    dtIsarFigure = plotting.draw_isar_img(dtIsarImages,dtIsarRangeAxes, ...
        dtIsarCrossAxes,'ApplyFftshiftDim1',false,'NormalizeDb',true, ...
        'CLimDb',[-40 0],'Titles',dtFigureTitles, ...
        'XLabel','Absolute range / m', ...
        'YLabel','Equivalent cross range / m', ...
        'ColorbarLabel','Normalized amplitude / dB');
    set(dtIsarFigure,'Name','DT_MD_simulation - ISAR comparison', ...
        'Color','w','Position',[100 80 1250 850]);

    dtMicroDopplerFigure = figure('Name', ...
        'DT_MD_simulation - micro-Doppler comparison','Color','w', ...
        'Position',[140 100 1250 850]);
    dtMicroLayout = tiledlayout(dtMicroDopplerFigure,2,2, ...
        'TileSpacing','compact','Padding','compact');
    title(dtMicroLayout,'Conical-target micro-Doppler comparison');
    for dtSelectedIndex = 1:dtSelectedModeCount
        nexttile(dtMicroLayout);
        dtModeForPlot = DT_MD_results.modes(dtSelectedIndex);
        plotting.spectrogram_microDoppler( ...
            dtModeForPlot.microDopplerSignal, ...
            1/dtConfig.pulseRepetitionIntervalSec, ...
            (dtConfig.pulseCount-1)/24);
        clim([-40 0]);
        title(sprintf('%s | %.1f r/min | BW %.1f Hz', ...
            dtModeForPlot.displayName, ...
            dtModeForPlot.microDoppler.equivalentRpm, ...
            dtModeForPlot.microDoppler.microDopplerBandwidthHz), ...
            'Interpreter','none');
    end

    if dtOptions.SaveResults
        DT_MD_results.outputFiles.isarPng = fullfile( ...
            dtOutputDirectory,'DT_MD_ISAR_comparison.png');
        DT_MD_results.outputFiles.isarFig = fullfile( ...
            dtOutputDirectory,'DT_MD_ISAR_comparison.fig');
        DT_MD_results.outputFiles.microDopplerPng = fullfile( ...
            dtOutputDirectory,'DT_MD_microDoppler_comparison.png');
        DT_MD_results.outputFiles.microDopplerFig = fullfile( ...
            dtOutputDirectory,'DT_MD_microDoppler_comparison.fig');
        exportgraphics(dtIsarFigure,DT_MD_results.outputFiles.isarPng, ...
            'Resolution',200);
        savefig(dtIsarFigure,DT_MD_results.outputFiles.isarFig);
        exportgraphics(dtMicroDopplerFigure, ...
            DT_MD_results.outputFiles.microDopplerPng,'Resolution',200);
        savefig(dtMicroDopplerFigure, ...
            DT_MD_results.outputFiles.microDopplerFig);
    end
end

if dtOptions.SaveResults
    DT_MD_results.outputFiles.matFile = fullfile( ...
        dtOutputDirectory,'DT_MD_results.mat');
    DT_MD_results.outputFiles.summaryCsv = fullfile( ...
