%% DT_MD_simulation - conical-target echo, ISAR, and micro-Doppler simulation
% This script reproduces the four 60 r/min conical-target motion cases used
% by the 2025 Hefei field experiment. Set DT_MD_options in the caller
% workspace before running this script to override the documented defaults.

dtScriptPath = mfilename('fullpath');
dtProjectRoot = fileparts(fileparts(dtScriptPath));
run(fullfile(dtProjectRoot,'startup_project.m'));

if ~exist('DT_MD_options','var') || isempty(DT_MD_options)
    DT_MD_options = struct();
end
dtDefaults = struct( ...
    'MotionModes',"ALL", ...
    'RunProfile',"reference", ...
    'ShowFigures',true, ...
    'SaveResults',true, ...
    'AddNoise',true, ...
    'SNRdB',0, ...
    'RandomSeed',20251107);
dtOptions = local_merge_options(dtDefaults,DT_MD_options);
local_validate_options(dtOptions);

dtRequiredFunctions = { ...
    'scatterermodel.createConicalMicroMotion', ...
    'scatterermodel.createRigidPointCloudTarget', ...
    'radar.echo_generate_target_lfm', ...
    'radar.lfm_local_reference_beat', ...
    'radar.range_migration_alignment', ...
    'radar.phase_cmp', ...
    'radar.ISAR_imaging', ...
    'radar.measure_micro_doppler', ...
    'radar.assess_isar_image_quality', ...
    'signal.crop_fft_bins', ...
    'plotting.draw_isar_img', ...
    'plotting.spectrogram_microDoppler'};
for dtFunctionIndex = 1:numel(dtRequiredFunctions)
    if isempty(which(dtRequiredFunctions{dtFunctionIndex}))
        error('RadarProject:DTMD:MissingLibraryFunction', ...
            'Required library function not found: %s', ...
            dtRequiredFunctions{dtFunctionIndex});
    end
end
dtCropFftBinsFcn = str2func('signal.crop_fft_bins');

%% Field-experiment waveform, geometry, and processing configuration
dtConfig = struct();
dtConfig.propagationSpeedMps = 3e8;
dtConfig.fLHz = 11.7e9;
dtConfig.fHHz = 17.9e9;
dtConfig.centerFrequencyHz = mean([dtConfig.fLHz,dtConfig.fHHz]);
dtConfig.bandwidthHz = dtConfig.fHHz-dtConfig.fLHz;
dtConfig.pulseWidthSec = 10e-6;
dtConfig.recordTimeSec = 10e-6;
dtConfig.pulseRepetitionIntervalSec = 5e-3;
dtConfig.referencePulseCount = 1000;
dtConfig.targetCenterRangeM = 2.2;
dtConfig.highRateSampleRateHz = 1e9;
dtConfig.beatSampleRateHz = 200e6;
dtConfig.rangeFftPoints = 4096;
dtConfig.rangeCropBins = 512;
dtConfig.isarSubaperturePulses = 16;
dtConfig.isarSlowTimeZeroPadding = 8;
dtConfig.coningHalfAngleRad = deg2rad(10);
dtConfig.swingAngleRangeRad = deg2rad([0 5]);
dtConfig.componentRateRadps = 2*pi;
dtConfig.truthRpm = 60;
dtConfig.initialAspectAngleRad = deg2rad(45);
dtConfig.addNoise = logical(dtOptions.AddNoise);
dtConfig.snrDb = double(dtOptions.SNRdB);
dtConfig.randomSeed = double(dtOptions.RandomSeed);
dtConfig.runProfile = lower(string(dtOptions.RunProfile));
if dtConfig.runProfile == "smoke"
    dtConfig.pulseCount = 64;
else
    dtConfig.pulseCount = dtConfig.referencePulseCount;
end
dtConfig.chirpRateHzPerSec = dtConfig.bandwidthHz/dtConfig.pulseWidthSec;
dtConfig.rangeBinSpacingM = dtConfig.propagationSpeedMps* ...
    (dtConfig.beatSampleRateHz/dtConfig.rangeFftPoints)/ ...
    (2*abs(dtConfig.chirpRateHzPerSec));
dtConfig.wavelengthM = dtConfig.propagationSpeedMps/ ...
    dtConfig.centerFrequencyHz;

[dtPointsBodyM,dtWeights,dtGeometryInfo] = local_cone_geometry();
dtInitialBodyToInertial = local_rotation_z(-dtConfig.initialAspectAngleRad);
dtGeometryInfo.initialBodyToInertial = dtInitialBodyToInertial;
dtGeometryInfo.targetCenterM = [0 dtConfig.targetCenterRangeM 0];
dtGeometryInfo.radarPositionM = [0 0 0];
dtGeometryInfo.lineOfSightAxis = "+Y";

dtCatalog = local_motion_catalog();
dtSelectedCatalogIndices = local_select_modes(dtOptions.MotionModes,dtCatalog);
dtSelectedModeCount = numel(dtSelectedCatalogIndices);

dtFastSampleCount = round(dtConfig.highRateSampleRateHz*dtConfig.recordTimeSec);
dtFastTimeSec = (0:dtFastSampleCount-1)/dtConfig.highRateSampleRateHz;
dtPulseTimeSec = (0:dtConfig.pulseCount-1)'* ...
    dtConfig.pulseRepetitionIntervalSec;
dtRadarState = struct('position_I',[0 0 0],'velocity_I',[0 0 0], ...
    'carrierFrequencyHz',dtConfig.centerFrequencyHz, ...
    'wavelengthM',dtConfig.wavelengthM,'dopplerSign',-1);

dtOutputDirectory = "";
if dtOptions.SaveResults
    dtOutputDirectory = string(local_create_output_directory( ...
        fullfile(dtProjectRoot,'results','DT_MD_simulation')));
end

dtModeResults = cell(dtSelectedModeCount,1);
dtSummaryMode = strings(dtSelectedModeCount,1);
dtSummaryName = strings(dtSelectedModeCount,1);
dtSummaryTruthRpm = repmat(dtConfig.truthRpm,dtSelectedModeCount,1);
dtSummaryEstimatedRpm = nan(dtSelectedModeCount,1);
dtSummaryRpmErrorPercent = nan(dtSelectedModeCount,1);
dtSummaryBandwidthHz = nan(dtSelectedModeCount,1);
dtSummaryFitR2 = nan(dtSelectedModeCount,1);
dtSummaryPeakRangeM = nan(dtSelectedModeCount,1);
dtSummaryIsarEntropy = nan(dtSelectedModeCount,1);
dtSummaryRangeWidthM = nan(dtSelectedModeCount,1);
dtSummaryCrossWidthM = nan(dtSelectedModeCount,1);

%% Process the four cases sequentially to bound peak memory use
for dtSelectedIndex = 1:dtSelectedModeCount
    dtCatalogIndex = dtSelectedCatalogIndices(dtSelectedIndex);
    dtMode = dtCatalog(dtCatalogIndex);
    fprintf('\nDT_MD_simulation: mode %d/%d - %s\n', ...
        dtSelectedIndex,dtSelectedModeCount,dtMode.displayName);

    dtMotionConfig = struct( ...
        'Mode',dtMode.motionMode, ...
        'PositionM',[0 dtConfig.targetCenterRangeM 0], ...
        'InitialBodyToInertial',dtInitialBodyToInertial, ...
        'ReferenceTimeSec',0, ...
        'SpinRateRadps',dtConfig.componentRateRadps, ...
        'ConingRateRadps',dtConfig.componentRateRadps, ...
        'ConingHalfAngleRad',dtConfig.coningHalfAngleRad, ...
        'SwingRateRadps',dtConfig.componentRateRadps, ...
        'SwingAngleMinRad',dtConfig.swingAngleRangeRad(1), ...
        'SwingAngleMaxRad',dtConfig.swingAngleRangeRad(2));
    [dtMotion,dtMotionTruth] = ...
        scatterermodel.createConicalMicroMotion(dtMotionConfig);
    dtTarget = scatterermodel.createRigidPointCloudTarget( ...
        dtPointsBodyM,dtWeights,dtMotion, ...
        struct('Name',"conicalTarget_"+dtMode.key));

    dtEchoRequest = struct( ...
        'pulseTimeSec',dtPulseTimeSec, ...
        'fastTimeSec',dtFastTimeSec, ...
        'f0Hz',dtConfig.fLHz, ...
        'f1Hz',dtConfig.fHHz, ...
        'fLoHz',0, ...
        'pulseWidthSec',dtConfig.pulseWidthSec, ...
        'deltaTauSec',0, ...
        'propagationSpeed',dtConfig.propagationSpeedMps, ...
        'waveformType','LFM', ...
        'pathLossMode','none', ...
        'targetAmplitude',1);
    dtEchoOptions = struct('Mode','stopAndGo','ReturnGroups',false, ...
        'ReturnPerTarget',false,'AutoFastTimeGate',true, ...
        'FastTimeChunkSize',4096,'ScattererChunkSize',64);
    [dtEcho,dtEchoInfo] = radar.echo_generate_target_lfm( ...
        dtTarget,dtRadarState,dtEchoRequest,dtEchoOptions);

    dtCleanEchoPower = mean(abs(dtEcho.total).^2,'all');
    dtNoisePower = 0;
    if dtConfig.addNoise
        dtNoisePower = dtCleanEchoPower/10^(dtConfig.snrDb/10);
        dtEcho.total = local_add_complex_noise(dtEcho.total,dtNoisePower, ...
            dtConfig.randomSeed+dtCatalogIndex);
    end
    dtPreviewPulseIndices = unique([1 ceil(dtConfig.pulseCount/2) ...
        dtConfig.pulseCount]);
    dtEchoPreview = struct('pulseIndices',dtPreviewPulseIndices, ...
        'pulseTimeSec',dtPulseTimeSec(dtPreviewPulseIndices), ...
        'fastTimeSec',dtFastTimeSec, ...
        'signal',dtEcho.total(dtPreviewPulseIndices,:));
    dtEchoInfo.cleanSignalPower = dtCleanEchoPower;
    dtEchoInfo.addedNoisePower = dtNoisePower;
    dtEchoInfo.requestedSnrDb = dtConfig.snrDb;

    dtBeatRequest = struct( ...
        'fastTimeSec',dtFastTimeSec, ...
        'referenceStartTimeSec',0, ...
        'f0Hz',dtConfig.fLHz, ...
        'f1Hz',dtConfig.fHHz, ...
        'pulseWidthSec',dtConfig.pulseWidthSec, ...
        'referenceDelaySec',0, ...
        'outputSampleRateHz',dtConfig.beatSampleRateHz);
    dtBeatOptions = struct( ...
        'Mode','ANALYTIC_IF', ...
        'RemoveMirrorFrequency',true, ...
        'RemoveSamplingAlias',true, ...
        'RemoveTimeOverlapCrosstalk',true, ...
        'RemoveDc',true, ...
        'LowpassCenterHz',50e6, ...
        'LowpassBandwidthHz',100e6, ...
        'FilterSuppressionDb',120, ...
        'ReturnPerTarget',false);
    [dtBeat,dtBeatInfo] = radar.lfm_local_reference_beat( ...
        {dtEcho.total},dtBeatRequest,dtBeatOptions);
    clear dtEcho

    dtRangeFft = fft(dtBeat.total,dtConfig.rangeFftPoints,2)/ ...
        size(dtBeat.total,2);
    dtFrequencyBinSpacingHz = dtConfig.beatSampleRateHz/ ...
        dtConfig.rangeFftPoints;
    dtExpectedBeatFrequencyHz = 2*abs(dtConfig.chirpRateHzPerSec)* ...
        dtConfig.targetCenterRangeM/dtConfig.propagationSpeedMps;
    dtCropCenterBin = round(dtExpectedBeatFrequencyHz/ ...
        dtFrequencyBinSpacingHz)+1;
    dtHrrfRaw = complex(zeros(dtConfig.pulseCount, ...
        dtConfig.rangeCropBins,'like',dtRangeFft));
    dtFirstCropBin = NaN;
    for dtPulseIndex = 1:dtConfig.pulseCount
        [dtHrrfRaw(dtPulseIndex,:),dtFirstCropBinThisPulse] = ...
            dtCropFftBinsFcn(dtRangeFft(dtPulseIndex,:), ...
            dtCropCenterBin,dtConfig.rangeCropBins);
        if dtPulseIndex == 1
            dtFirstCropBin = dtFirstCropBinThisPulse;
        end
    end
    clear dtRangeFft dtBeat

    dtAbsoluteFrequencyAxisHz = (dtFirstCropBin-1 + ...
        (0:dtConfig.rangeCropBins-1))*dtFrequencyBinSpacingHz;
    dtAbsoluteRangeAxisM = dtAbsoluteFrequencyAxisHz* ...
        dtConfig.propagationSpeedMps/(2*abs(dtConfig.chirpRateHzPerSec));
    dtAlignmentGate = find(abs(dtAbsoluteRangeAxisM- ...
        dtConfig.targetCenterRangeM) <= dtTarget.boundingRadiusM+0.25);
    dtCroppedTimeWave = dtConfig.rangeCropBins*ifft( ...
        ifftshift(dtHrrfRaw,2),dtConfig.rangeCropBins,2);
    [~,dtHrrfAligned,dtRangeMigrationBins] = ...
        radar.range_migration_alignment(dtCroppedTimeWave,dtHrrfRaw, ...
        'freq',dtAlignmentGate,true);
    clear dtCroppedTimeWave

    dtMicroDopplerGate = find(abs(dtAbsoluteRangeAxisM- ...
        dtConfig.targetCenterRangeM) <= dtTarget.boundingRadiusM+ ...
        2*dtConfig.rangeBinSpacingM);
    dtMicroDopplerSignal = sum( ...
        dtHrrfAligned(:,dtMicroDopplerGate),2);
    dtMicroDopplerSignal = dtMicroDopplerSignal-mean(dtMicroDopplerSignal);
    dtMeasurementOptions = struct( ...
        'GaussianAlpha',(dtConfig.pulseCount-1)/24, ...
        'FrequencySearchHz',[0.4 3], ...
        'MaxHarmonic',5, ...
        'SubharmonicFitRatio',0.95, ...
        'MinFundamentalPowerFraction',0.05, ...
        'HarmonicFitLowpassHz',5, ...
        'EnergyFraction',0.99);
    dtMicroDoppler = radar.measure_micro_doppler( ...
        dtMicroDopplerSignal,dtPulseTimeSec,dtMeasurementOptions);

    dtSubapertureCount = min(dtConfig.isarSubaperturePulses, ...
        dtConfig.pulseCount);
    dtSubapertureStart = floor((dtConfig.pulseCount- ...
        dtSubapertureCount)/2)+1;
    dtSubapertureIndices = dtSubapertureStart: ...
        (dtSubapertureStart+dtSubapertureCount-1);
    dtIsarInput = dtHrrfAligned( ...
        dtSubapertureIndices,dtMicroDopplerGate);
    dtPhaseCompensated = radar.phase_cmp(dtIsarInput,0.12);
    dtPhaseReferenceMode = "VARIANCE_UNIT";
    if any(~isfinite(dtPhaseCompensated(:)))
        warning('RadarProject:DTMD:InvalidPhaseCompensation', ...
            ['Mode %s produced an invalid phase reference; the ISAR image ', ...
             'uses the aligned, uncompensated subaperture.'],dtMode.key);
        dtPhaseCompensated = dtIsarInput;
        dtPhaseReferenceMode = "NONE_INVALID_REFERENCE";
    end
    dtIsarImage = radar.ISAR_imaging(dtPhaseCompensated, ...
        dtConfig.isarSlowTimeZeroPadding,'NO');
    if any(~isfinite(dtIsarImage(:)))
        error('RadarProject:DTMD:InvalidIsarImage', ...
            'Mode %s produced NaN/Inf in the ISAR image.',dtMode.key);
    end
    dtDopplerBinCount = size(dtIsarImage,1);
    dtDopplerAxisHz = ((0:dtDopplerBinCount-1)- ...
        floor(dtDopplerBinCount/2))/(dtDopplerBinCount* ...
        dtConfig.pulseRepetitionIntervalSec);
    dtEquivalentCrossRangeAxisM = dtConfig.wavelengthM*dtDopplerAxisHz/ ...
        (2*dtConfig.componentRateRadps);
    dtIsarRangeAxisM = dtAbsoluteRangeAxisM(dtMicroDopplerGate);
    dtIsarQuality = radar.assess_isar_image_quality(dtIsarImage, ...
        dtIsarRangeAxisM,dtEquivalentCrossRangeAxisM,struct());

    dtMeanRangeProfile = mean(abs(dtHrrfAligned),1);
    [~,dtPeakRangeIndex] = max(dtMeanRangeProfile);
    dtPeakRangeM = dtAbsoluteRangeAxisM(dtPeakRangeIndex);

    dtModeResult = struct();
    dtModeResult.mode = dtMode.key;
    dtModeResult.displayName = dtMode.displayName;
    dtModeResult.externalExperimentGroup = dtMode.externalExperimentGroup;
    dtModeResult.motionTruth = dtMotionTruth;
    dtModeResult.echoPreview = dtEchoPreview;
    dtModeResult.echoInfo = dtEchoInfo;
    dtModeResult.beatInfo = dtBeatInfo;
    dtModeResult.hrrf = struct('raw',dtHrrfRaw, ...
        'aligned',dtHrrfAligned,'absoluteRangeAxisM',dtAbsoluteRangeAxisM, ...
        'rangeMigrationBins',dtRangeMigrationBins, ...
        'alignmentGateIndices',dtAlignmentGate, ...
        'microDopplerGateIndices',dtMicroDopplerGate, ...
        'meanPeakRangeM',dtPeakRangeM);
    dtModeResult.microDopplerSignal = dtMicroDopplerSignal;
    dtModeResult.microDoppler = dtMicroDoppler;
    dtModeResult.isar = struct('image',dtIsarImage, ...
        'absoluteRangeAxisM',dtIsarRangeAxisM, ...
        'dopplerAxisHz',dtDopplerAxisHz, ...
        'equivalentCrossRangeAxisM',dtEquivalentCrossRangeAxisM, ...
        'subaperturePulseIndices',dtSubapertureIndices, ...
        'phaseCompensatedHrrf',dtPhaseCompensated, ...
        'phaseReferenceMode',dtPhaseReferenceMode, ...
        'quality',dtIsarQuality);
    dtModeResults{dtSelectedIndex} = dtModeResult;

    dtSummaryMode(dtSelectedIndex) = dtMode.key;
    dtSummaryName(dtSelectedIndex) = dtMode.displayName;
    dtSummaryEstimatedRpm(dtSelectedIndex) = dtMicroDoppler.equivalentRpm;
    dtSummaryRpmErrorPercent(dtSelectedIndex) = 100* ...
        abs(dtMicroDoppler.equivalentRpm-dtConfig.truthRpm)/ ...
        dtConfig.truthRpm;
    dtSummaryBandwidthHz(dtSelectedIndex) = ...
        dtMicroDoppler.microDopplerBandwidthHz;
    dtSummaryFitR2(dtSelectedIndex) = dtMicroDoppler.harmonicFitR2;
    dtSummaryPeakRangeM(dtSelectedIndex) = dtPeakRangeM;
    dtSummaryIsarEntropy(dtSelectedIndex) = dtIsarQuality.entropy;
    dtSummaryRangeWidthM(dtSelectedIndex) = dtIsarQuality.range3dBWidth;
    dtSummaryCrossWidthM(dtSelectedIndex) = ...
        dtIsarQuality.crossRange3dBWidth;

    fprintf('  estimated %.3f r/min, bandwidth %.3f Hz, peak range %.3f m\n', ...
        dtMicroDoppler.equivalentRpm, ...
        dtMicroDoppler.microDopplerBandwidthHz,dtPeakRangeM);
    clear dtHrrfRaw dtHrrfAligned dtPhaseCompensated dtIsarImage
end

DT_MD_summary = table(dtSummaryMode,dtSummaryName,dtSummaryTruthRpm, ...
    dtSummaryEstimatedRpm,dtSummaryRpmErrorPercent,dtSummaryBandwidthHz, ...
    dtSummaryFitR2,dtSummaryPeakRangeM,dtSummaryIsarEntropy, ...
    dtSummaryRangeWidthM,dtSummaryCrossWidthM, ...
    'VariableNames',{'Mode','Name','TruthRpm','EstimatedRpm', ...
    'RpmErrorPercent','MicroDopplerBandwidthHz','HarmonicFitR2', ...
    'MeanPeakRangeM','IsarEntropy','Range3dBWidthM', ...
    'CrossRange3dBWidthM'});

