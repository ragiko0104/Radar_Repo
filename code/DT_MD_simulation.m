function merged = local_merge_options(defaults,overrides)
if ~(isstruct(overrides) && isscalar(overrides))
    error('RadarProject:DTMD:InvalidOptions', ...
        'DT_MD_options must be a scalar struct.');
end
merged = defaults;
names = fieldnames(overrides);
for k = 1:numel(names)
    if ~isfield(defaults,names{k})
        error('RadarProject:DTMD:UnknownOption', ...
            'Unknown DT_MD_options field: %s',names{k});
    end
    merged.(names{k}) = overrides.(names{k});
end
end

function local_validate_options(options)
profile = lower(string(options.RunProfile));
if ~(isscalar(profile) && ismember(profile,["reference","smoke"]))
    error('RadarProject:DTMD:InvalidRunProfile', ...
        'RunProfile must be "reference" or "smoke".');
end
local_logical_option(options.ShowFigures,'ShowFigures');
local_logical_option(options.SaveResults,'SaveResults');
local_logical_option(options.AddNoise,'AddNoise');
if ~(isnumeric(options.SNRdB) && isreal(options.SNRdB) && ...
        isscalar(options.SNRdB) && isfinite(options.SNRdB))
    error('RadarProject:DTMD:InvalidSnr', ...
        'SNRdB must be a finite real scalar.');
end
if ~(isnumeric(options.RandomSeed) && isreal(options.RandomSeed) && ...
        isscalar(options.RandomSeed) && isfinite(options.RandomSeed) && ...
        options.RandomSeed >= 0 && options.RandomSeed == round(options.RandomSeed))
    error('RadarProject:DTMD:InvalidRandomSeed', ...
        'RandomSeed must be a nonnegative integer scalar.');
end
end

function value = local_logical_option(value,name)
if ~(isscalar(value) && (islogical(value) || ...
        (isnumeric(value) && isreal(value) && isfinite(value) && ...
        any(value == [0 1]))))
    error('RadarProject:DTMD:InvalidLogicalOption', ...
        '%s must be a logical scalar.',name);
end
value = logical(value);
end

function [points,weights,info] = local_cone_geometry()
radiiM = [0.1 0.15 0.2 0.2];
ringYM = [0 0.25 0.5 0.5];
azimuthRad = deg2rad(136)+[2*pi/3 4*pi/3];
points = zeros(1+2*numel(radiiM),3);
points(1,:) = [0 -0.5 0];
row = 2;
for ringIndex = 1:numel(radiiM)
    for pointIndex = 1:numel(azimuthRad)
        points(row,:) = [radiiM(ringIndex)*cos(azimuthRad(pointIndex)), ...
            ringYM(ringIndex), ...
            radiiM(ringIndex)*sin(azimuthRad(pointIndex))];
        row = row+1;
    end
end
weights = ones(size(points,1),1)/sqrt(size(points,1));
info = struct('description', ...
    "Field-test tip plus four two-point axial rings", ...
    'longitudinalBodyAxis',"+Y",'initialConingTiltBodyAxis',"+Z", ...
    'swingInertialAxis',"+Z",'ringRadiiM',radiiM, ...
    'ringLongitudinalPositionsM',ringYM,'ringAzimuthRad',azimuthRad, ...
    'scattererCount',size(points,1),'weightNormalization',"unit L2 norm");
end

function catalog = local_motion_catalog()
catalog = repmat(struct('key',"",'motionMode',"",'displayName',"", ...
    'externalExperimentGroup',""),4,1);
catalog(1) = struct('key',"spin",'motionMode',"spin", ...
    'displayName',"60 r/min pure spin",'externalExperimentGroup',"141");
catalog(2) = struct('key',"coneSpin",'motionMode',"coneSpin", ...
    'displayName',"60 r/min coning + spin",'externalExperimentGroup',"221");
catalog(3) = struct('key',"swingSpin",'motionMode',"swingSpin", ...
    'displayName',"60 r/min swing + spin",'externalExperimentGroup',"241");
catalog(4) = struct('key',"coneSwingSpin",'motionMode',"coneSwingSpin", ...
    'displayName',"60 r/min coning + swing + spin", ...
    'externalExperimentGroup',"261");
end

function selected = local_select_modes(request,catalog)
if isnumeric(request)
    selected = double(request(:).');
    if isempty(selected) || any(selected < 1 | selected > numel(catalog) | ...
            selected ~= round(selected))
        error('RadarProject:DTMD:InvalidMotionModes', ...
            'Numeric MotionModes must contain catalog indices 1 through 4.');
    end
    selected = unique(selected,'stable');
    return;
end
if ischar(request)
    requested = string({request});
else
    requested = string(request(:));
end
if isempty(requested) || any(strlength(strtrim(requested)) == 0)
    error('RadarProject:DTMD:InvalidMotionModes', ...
        'MotionModes must not be empty.');
end
if any(strcmpi(strtrim(requested),"ALL"))
    selected = 1:numel(catalog);
    return;
end
selected = zeros(1,numel(requested));
for k = 1:numel(requested)
    token = lower(regexprep(char(strtrim(requested(k))),'[^a-zA-Z0-9]',''));
    switch token
        case {'spin','spinonly','141','1'}
            selected(k) = 1;
        case {'conespin','coningspin','221','2'}
            selected(k) = 2;
        case {'swingspin','241','3'}
            selected(k) = 3;
        case {'coneswingspin','combined','261','4'}
            selected(k) = 4;
        otherwise
            error('RadarProject:DTMD:InvalidMotionModes', ...
                'Unsupported MotionModes entry: %s',requested(k));
    end
end
selected = unique(selected,'stable');
end

function C = local_rotation_z(angleRad)
C = [cos(angleRad),-sin(angleRad),0; ...
    sin(angleRad),cos(angleRad),0;0,0,1];
end

function signal = local_add_complex_noise(signal,noisePower,randomSeed)
rng(randomSeed,'twister');
rowChunk = 16;
noiseScale = sqrt(noisePower/2);
for rowStart = 1:rowChunk:size(signal,1)
    rows = rowStart:min(rowStart+rowChunk-1,size(signal,1));
    noise = noiseScale*(randn(numel(rows),size(signal,2))+ ...
        1i*randn(numel(rows),size(signal,2)));
    signal(rows,:) = signal(rows,:)+noise;
end
end

function outputDirectory = local_create_output_directory(baseDirectory)
if exist(baseDirectory,'dir') ~= 7
    mkdir(baseDirectory);
end
stamp = char(datetime('now','Format','yyyyMMdd_HHmmss'));
outputDirectory = fullfile(baseDirectory,stamp);
suffix = 0;
while exist(outputDirectory,'dir') == 7
    suffix = suffix+1;
    outputDirectory = fullfile(baseDirectory, ...
        sprintf('%s_%03d',stamp,suffix));
end
mkdir(outputDirectory);
end
