    'isarPng',"",'isarFig',"",'microDopplerPng',"", ...
    'microDopplerFig',"");

%% Final result figures: ISAR comparison followed by micro-Doppler comparison
if dtOptions.ShowFigures
    dtIsarImages = cell(1,dtSelectedModeCount);
    dtIsarRangeAxes = cell(1,dtSelectedModeCount);
    dtIsarCrossAxes = cell(1,dtSelectedModeCount);
    dtFigureTitles = strings(1,dtSelectedModeCount);
    for dtSelectedIndex = 1:dtSelectedModeCount
        dtIsarImages{dtSelectedIndex} = ...
            DT_MD_results.modes(dtSelectedIndex).isar.image;
